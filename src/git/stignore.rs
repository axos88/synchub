//! The generated .stignore-git lists, and the lines in .stignore that use them.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use crate::paths;

pub const LIST: &str = ".stignore-git";

const KEEP_BEGIN: &str = "// sttools git: begin - keep the generated ignore lists synced";
const INCLUDE_BEGIN: &str = "// sttools git: begin - ignore what git ignores";
const END: &str = "// sttools git: end";

/// Files Syncthing manages itself; they never go into a list.
pub fn is_syncthing_file(path: &Path) -> bool {
    path.components().any(|c| {
        matches!(
            c.as_os_str().to_str(),
            Some(".stfolder" | ".stversions" | ".stignore" | LIST)
        )
    })
}

/// A pattern matching exactly `rel` (relative to the folder root) and, if it's a directory, its contents.
pub fn anchored(rel: &str) -> String {
    let mut pattern = String::from("/");
    for c in rel.chars() {
        if matches!(c, '*' | '?' | '[' | ']' | '{' | '}' | '\\') {
            pattern.push('\\');
        }
        pattern.push(c);
    }
    pattern
}

/// The paths (relative to the folder root) a .stignore-git lists; the inverse of [`anchored`].
pub fn listed(list: &str) -> Vec<String> {
    list.lines()
        .filter(|line| !line.starts_with("//"))
        .filter_map(|line| line.strip_prefix('/'))
        .map(|pattern| {
            let mut rel = String::new();
            let mut chars = pattern.chars();
            while let Some(c) = chars.next() {
                rel.push(if c == '\\' {
                    chars.next().unwrap_or(c)
                } else {
                    c
                });
            }
            rel
        })
        .collect()
}

/// The contents of a .stignore-git listing what git ignores in the repository at `source` (relative to the folder root).
pub fn list_file(source: &str, patterns: &[String]) -> String {
    let source = if source.is_empty() {
        "the folder root".to_string()
    } else {
        format!("/{source}")
    };
    let mut text = format!(
        "// What git ignores in {source}, generated by `sttools git` (stgit); don't edit.\n\
         // Syncthing syncs this file; each device's .stignore #includes it.\n"
    );
    for pattern in patterns {
        text.push_str(pattern);
        text.push('\n');
    }
    text
}

/// `stignore` with the managed blocks covering `lists`, plus the lists it
/// already covered that still exist. Lines outside the blocks are kept as
/// they are.
///
/// The `!` lines keeping the lists synced go first, because the first
/// matching pattern wins; the includes go last, so that the user's own `!`
/// lines win over them.
pub fn with_lists(stignore: &str, root: &Path, lists: &[PathBuf]) -> String {
    let mut own = Vec::new();
    let mut included = BTreeSet::new();
    let mut block = None;
    for line in stignore.lines() {
        match (block, line) {
            (None, KEEP_BEGIN | INCLUDE_BEGIN) => block = Some(line),
            (None, _) => own.push(line),
            (Some(_), END) => block = None,
            (Some(INCLUDE_BEGIN), _) => {
                if let Some(rel) = line.strip_prefix("#include ") {
                    let rel = rel.trim();
                    if root.join(rel).is_file() {
                        included.insert(rel.to_string());
                    }
                }
            }
            (Some(_), _) => {}
        }
    }
    included.extend(lists.iter().map(|list| paths::relative(list, root)));

    while own.first().is_some_and(|l| l.trim().is_empty()) {
        own.remove(0);
    }
    while own.last().is_some_and(|l| l.trim().is_empty()) {
        own.pop();
    }
    if included.is_empty() {
        return if own.is_empty() {
            String::new()
        } else {
            own.join("\n") + "\n"
        };
    }

    let mut out = vec![KEEP_BEGIN.to_string()];
    out.extend(included.iter().map(|rel| format!("!{}", anchored(rel))));
    out.push(END.to_string());
    if !own.is_empty() {
        out.push(String::new());
        out.extend(own.iter().map(|l| l.to_string()));
    }
    out.push(String::new());
    out.push(INCLUDE_BEGIN.to_string());
    out.extend(included.iter().map(|rel| format!("#include {rel}")));
    out.push(END.to_string());
    out.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    fn scratch(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("sttools-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn anchored_escapes_glob_characters() {
        assert_eq!(anchored("ui/dist"), "/ui/dist");
        assert_eq!(anchored("a[1]*?{x}\\b"), "/a\\[1\\]\\*\\?\\{x\\}\\\\b");
    }

    #[test]
    fn listed_reverses_anchored() {
        let rels = ["ui/dist", "a[1]*?{x}\\b", "weird name.log"];
        let text = list_file("", &rels.map(anchored));
        assert_eq!(listed(&text), rels);
    }

    #[test]
    fn syncthing_files_are_recognised() {
        assert!(is_syncthing_file(Path::new("/r/.stignore-git")));
        assert!(is_syncthing_file(Path::new("/r/.stversions/x")));
        assert!(!is_syncthing_file(Path::new("/r/.stignore-gitx")));
    }

    #[test]
    fn adds_blocks_around_own_lines() {
        let root = scratch("blocks");
        let list = root.join("app").join(LIST);
        let out = with_lists("// mine\n/tmp\n!/keep\n", &root, &[list]);
        assert_eq!(
            out,
            format!(
                "{KEEP_BEGIN}\n!/app/.stignore-git\n{END}\n\n// mine\n/tmp\n!/keep\n\n{INCLUDE_BEGIN}\n#include app/.stignore-git\n{END}\n"
            )
        );
    }

    #[test]
    fn is_idempotent() {
        let root = scratch("idempotent");
        let lists = [root.join(LIST)];
        let once = with_lists("/tmp\n", &root, &lists);
        assert_eq!(with_lists(&once, &root, &lists), once);
    }

    #[test]
    fn keeps_existing_lists_and_drops_vanished_ones() {
        let root = scratch("vanished");
        fs::create_dir_all(root.join("a")).unwrap();
        fs::write(root.join("a").join(LIST), "").unwrap();
        let both = with_lists(
            "",
            &root,
            &[root.join("a").join(LIST), root.join("b").join(LIST)],
        );
        let again = with_lists(&both, &root, &[root.join("c").join(LIST)]);
        assert!(again.contains("#include a/.stignore-git"));
        assert!(!again.contains("b/.stignore-git"));
        assert!(again.contains("#include c/.stignore-git"));
    }

    #[test]
    fn list_file_names_its_source() {
        let text = list_file("ruby/heroku", &["/ruby/heroku/tmp".to_string()]);
        assert!(text.starts_with("// What git ignores in /ruby/heroku,"));
        assert!(text.ends_with("\n/ruby/heroku/tmp\n"));
    }
}
