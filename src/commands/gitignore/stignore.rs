//! A folder's generated lists - .stignore-git, synced, and
//! .stignore-git-local, this device's own, which the synced one includes -
//! and the line in .stignore that includes them.

use std::collections::BTreeMap;
use std::path::Path;

use itertools::Itertools;
pub const FILE_NAME: &str = ".stignore-git";
pub const LOCAL_FILE_NAME: &str = ".stignore-git-local";

/// The one line .stignore needs.
const INCLUDE: &str = "#include .stignore-git";

/// What starts a repository's section, followed by its path relative to
/// the folder's root: `.` for the root, `..` above it.
const SECTION: &str = "// repo ";
/// What ends the header of the section of a repository's tracked files.
const TRACKED: &str = ": tracked";

/// A pattern matching exactly `rel` (relative to the folder root) and, if it's a directory, its contents.
pub fn anchored(rel: &str) -> String {
    std::iter::once('/')
        .chain(rel.chars().flat_map(|c| {
            let escape = matches!(c, '*' | '?' | '[' | ']' | '{' | '}' | '\\');
            escape.then_some('\\').into_iter().chain([c])
        }))
        .collect()
}

/// A repository's part of a list.
#[derive(Default, Debug, PartialEq)]
pub struct Section {
    /// `!` lines keeping the tracked files the patterns match synced.
    pub tracked: Vec<String>,
    pub patterns: Vec<String>,
}

/// One of a folder's lists: a section per repository, by its path relative
/// to the folder's root.
#[derive(Default, Debug, PartialEq)]
pub struct List {
    pub sections: BTreeMap<String, Section>,
}

impl List {
    pub fn parse(text: &str) -> Self {
        let mut list = List::default();
        // Before the first section: the header, which is written anew.
        let mut current: Option<(String, bool)> = None;
        text.lines().for_each(|line| {
            if let Some(header) = line.strip_prefix(SECTION) {
                current = Some(match header.strip_suffix(TRACKED) {
                    Some(repo) => (repo.to_string(), true),
                    None => (header.to_string(), false),
                });
            } else if let Some((repo, tracked)) = &current
                && !line.starts_with("//")
                && !line.starts_with("#include ")
            {
                let section = list.sections.entry(repo.clone()).or_default();
                let lines = if *tracked {
                    &mut section.tracked
                } else {
                    &mut section.patterns
                };
                lines.push(line.to_string());
            }
        });
        list
    }

    /// The synced list: kept synced itself, and the local one not synced -
    /// at any depth, as a nested folder's are in this one too; then every
    /// repository's tracked files - Syncthing lets the first matching pattern
    /// win, and git never ignores those - then the patterns, the innermost
    /// repository first; last, the local list - a .gitignore wins over this
    /// device's own excludes, as in git. Syncthing fails on a missing
    /// included file, so the local list is always written with it.
    pub fn render_synced(&self) -> String {
        let header = format!(
            "// What git ignores in this folder, generated by `synchub gitignore`; don't edit.\n\
             // Syncthing syncs this file; each device's .stignore #includes it.\n\
             !{}\n{}\n",
            FILE_NAME, LOCAL_FILE_NAME
        );
        let sections = self.innermost_first();
        let tracked = sections
            .iter()
            .filter(|(_, section)| !section.tracked.is_empty())
            .map(|(repo, section)| block(&format!("{SECTION}{repo}{TRACKED}"), &section.tracked));
        let patterns = sections
            .iter()
            .map(|(repo, section)| block(&format!("{SECTION}{repo}"), &section.patterns));
        let local = format!("// this device's own excludes\n#include {LOCAL_FILE_NAME}\n");
        tracked
            .chain(patterns)
            .chain([local])
            .fold(header, |text, block| text + &block)
    }

    /// The local list: this device's own excludes.
    pub fn render_local(&self) -> String {
        let header = String::from(
            "// What this device's git ignores besides the .gitignore files (info/exclude,\n\
             // core.excludesFile), generated by `synchub gitignore`; don't edit. Not synced.\n",
        );
        self.innermost_first()
            .iter()
            .map(|(repo, section)| block(&format!("{SECTION}{repo}"), &section.patterns))
            .fold(header, |text, block| text + &block)
    }

    /// The sections, the deepest repository first: its rules decide inside it.
    fn innermost_first(&self) -> Vec<(&String, &Section)> {
        self.sections
            .iter()
            .sorted_by_key(|(repo, _)| std::cmp::Reverse(depth(repo)))
            .collect()
    }

    pub fn patterns(&self) -> usize {
        self.sections.values().map(|s| s.patterns.len()).sum()
    }

    pub fn tracked(&self) -> usize {
        self.sections.values().map(|s| s.tracked.len()).sum()
    }
}

/// How far below the folder's root a section's repository is; negative above it.
fn depth(repo: &str) -> isize {
    Path::new(repo)
        .components()
        .map(|c| match c {
            std::path::Component::ParentDir => -1,
            std::path::Component::Normal(_) => 1,
            _ => 0,
        })
        .sum()
}

fn block(header: &str, lines: &[String]) -> String {
    lines
        .iter()
        .fold(format!("{header}\n"), |text, line| text + line + "\n")
}

/// `stignore` with the [`INCLUDE`] line, appended if missing: last, so the
/// user's own `!` lines win over the generated patterns.
pub fn with_include(stignore: &str) -> String {
    if stignore.lines().any(|line| line.trim() == INCLUDE) {
        return stignore.to_string();
    }
    let mut text = stignore.to_string();
    if !text.is_empty() && !text.ends_with('\n') {
        text.push('\n');
    }
    text + INCLUDE + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    fn lines(text: &[&str]) -> Vec<String> {
        text.iter().map(|s| s.to_string()).collect()
    }

    #[test]
    fn anchored_escapes_glob_characters() {
        assert_eq!(anchored("ui/dist"), "/ui/dist");
        assert_eq!(anchored("a[1]*?{x}\\b"), "/a\\[1\\]\\*\\?\\{x\\}\\\\b");
    }

    #[test]
    fn the_synced_list_keeps_tracked_files_first_and_the_innermost_repository_first() {
        let list = List {
            sections: BTreeMap::from([
                (
                    ".".to_string(),
                    Section {
                        tracked: lines(&["!/vendor/kept"]),
                        patterns: lines(&["vendor/", "*.log"]),
                    },
                ),
                (
                    "sub/repo".to_string(),
                    Section {
                        tracked: Vec::new(),
                        patterns: lines(&["/sub/repo/tmp/"]),
                    },
                ),
                (
                    "..".to_string(),
                    Section {
                        tracked: Vec::new(),
                        patterns: lines(&["*.bak"]),
                    },
                ),
            ]),
        };
        let text = list.render_synced();
        let body: Vec<&str> = text
            .lines()
            .filter(|l| !l.starts_with("// What") && !l.starts_with("// Syncthing"))
            .collect();
        assert_eq!(
            body,
            [
                "!.stignore-git",
                ".stignore-git-local",
                "// repo .: tracked",
                "!/vendor/kept",
                "// repo sub/repo",
                "/sub/repo/tmp/",
                "// repo .",
                "vendor/",
                "*.log",
                "// repo ..",
                "*.bak",
                "// this device's own excludes",
                "#include .stignore-git-local",
            ]
        );
        assert_eq!(List::parse(&text), list);
    }

    #[test]
    fn with_include_appends_once() {
        assert_eq!(with_include(""), "#include .stignore-git\n");
        assert_eq!(with_include("/tmp"), "/tmp\n#include .stignore-git\n");
        let once = with_include("// mine\n!/keep\n");
        assert_eq!(once, "// mine\n!/keep\n#include .stignore-git\n");
        assert_eq!(with_include(&once), once);
    }
}
